#!/usr/bin/env python3
"""Regenerates src/app/constants/everyday-words.ts.

Takes the most frequent English words from `wordfreq`, tags each as a noun,
verb or adjective with WordNet, and keeps only everyday base forms.

Setup: python3 -m venv .venv && .venv/bin/pip install wordfreq nltk
Run:   .venv/bin/python scripts/generate-everyday-words.py
Then:  pnpm exec prettier --write src/app/constants/everyday-words.ts
"""
import json
from pathlib import Path

import nltk
from nltk.corpus import stopwords
from nltk.corpus import wordnet as wn
from wordfreq import top_n_list

TOP_WORDS = 3500
MIN_LENGTH = 3
OUTPUT = Path(__file__).resolve().parent.parent / "src/app/constants/everyday-words.ts"

# WordNet part-of-speech tag -> WORD_TYPE value in language-learning-words.ts.
# Adjective satellites ("s") count as adjectives.
POS_TYPE = {"n": "noun", "v": "verb", "a": "adjective"}

# Frequent but not useful as vocabulary cards: numerals, a few words that are
# vulgar, web or ambiguous, and function-like leftovers WordNet still lists.
SKIP = set(
    """one two three four five six seven eight nine ten eleven twelve twenty
    thirty forty fifty hundred thousand million billion first second third
    may yea bloody podcast format steam fuck damn shit hell sex porn gay
    semi mid ago another someone less much""".split()
)

# Phrases are not derivable from a word list, so they are written by hand.
PHRASES = [
    "thank you", "please", "sorry", "excuse me", "good morning", "good night",
    "good luck", "you're welcome", "how are you", "see you later",
    "nice to meet you", "I don't know", "I understand", "I'm hungry",
    "I'm tired", "where is the bathroom", "how much is it", "help me",
    "what is your name", "no problem", "of course", "happy birthday",
    "cheers", "welcome", "goodbye",
]  # fmt: skip


def dominant_pos(word):
    """Part of speech whose WordNet senses of the exact lowercase word are
    most frequent, or None when it is not a noun, verb or adjective."""
    counts = {}
    for synset in wn.synsets(word):
        pos = "a" if synset.pos() in ("a", "s") else synset.pos()
        if pos not in POS_TYPE:
            continue
        for lemma in synset.lemmas():
            # Case-sensitive match drops proper nouns such as "Adams".
            if lemma.name() == word:
                counts[pos] = counts.get(pos, 0) + lemma.count() + 0.01
    return max(counts, key=counts.get) if counts else None


def is_base_form(word):
    """False for plurals, participles, comparatives and other inflections."""
    return all(wn.morphy(word, pos) in (None, word) for pos in POS_TYPE)


def build_words():
    for corpus in ("wordnet", "stopwords"):
        nltk.download(corpus, quiet=True)
    stop = set(stopwords.words("english"))

    by_type = {pos_type: [] for pos_type in POS_TYPE.values()}
    for word in top_n_list("en", TOP_WORDS):
        if (
            len(word) < MIN_LENGTH
            or not word.isalpha()
            or word in stop
            or word in SKIP
            or not is_base_form(word)
        ):
            continue
        pos = dominant_pos(word)
        if pos:
            by_type[POS_TYPE[pos]].append(word)
    return by_type


def render(by_type):
    lines = [
        "import { WORD_TYPE, type WordType } from './language-learning-words';",
        "",
        "// Frequency-ranked everyday English base forms (most common first), drawn from",
        "// the top of the wordfreq list and filtered through WordNet to drop proper",
        "// nouns, inflected forms and function words. Phrases are written by hand.",
        "// Generated by scripts/generate-everyday-words.py; regenerate instead of editing.",
        "// Word ranking from wordfreq (https://github.com/rspeer/wordfreq, Apache-2.0;",
        "// data CC BY-SA 4.0), built on Google Books Ngrams, Wikipedia, OpenSubtitles",
        "// and SUBTLEX (Brysbaert et al.).",
        "export const EVERYDAY_WORDS: Record<WordType, string[]> = {",
    ]
    for key, words in (
        ("NOUN", by_type["noun"]),
        ("ADJECTIVE", by_type["adjective"]),
        ("VERB", by_type["verb"]),
        ("PHRASE", PHRASES),
    ):
        lines.append(f"  [WORD_TYPE.{key}]: {json.dumps(words)},")
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    by_type = build_words()
    OUTPUT.write_text(render(by_type))
    print({pos_type: len(words) for pos_type, words in by_type.items()})
